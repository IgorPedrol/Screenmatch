-- V1: schema inicial do ScreenMatch
-- Espelha as entidades JPA Serie (tabela series) e Episodio (tabela episodios).
-- Caminho no projeto: src/main/resources/db/migration/

CREATE TABLE series (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    titulo           VARCHAR(255) NOT NULL,
    total_temporadas SMALLINT NOT NULL,
    avaliacao        DOUBLE PRECISION,
    genero           VARCHAR(255),   -- enum Categoria gravado como texto (EnumType.STRING)
    atores           VARCHAR(255),
    poster           VARCHAR(255),
    sinopse          VARCHAR(255),
    CONSTRAINT pk_series PRIMARY KEY (id)
);

CREATE TABLE episodios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    temporada       SMALLINT     NOT NULL,
    titulo          VARCHAR(255) NOT NULL,
    numero_episodio INTEGER      NOT NULL,
    avaliacao       DOUBLE PRECISION,
    data_lancamento DATE,
    serie_id        BIGINT,
    CONSTRAINT pk_episodios PRIMARY KEY (id),
    CONSTRAINT fk_episodios_serie FOREIGN KEY (serie_id) REFERENCES series (id)
);

-- O PostgreSQL não cria índice automaticamente para chaves estrangeiras.
CREATE INDEX idx_episodios_serie_id ON episodios (serie_id);